<?php

namespace App\Services;

use Carbon\Carbon;
use Database\Seeders\VersionUpdateSeeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Schema;
use Symfony\Component\Process\Process;

/**
 * Deployment Inspector Service
 *
 * Inspects application versions, Git/CI-CD deployment metadata,
 * pending database migrations, and runtime readiness for System Updater.
 * @author Renatus Bernardo
 */
class DeploymentInspectorService
{
    /**
     * Collect installed database version, codebase version, and runtime stack info.
     */
    public function getSystemVersions(): array
    {
        $dbVersion = '1.0.0';

        if (Schema::hasTable('platform_settings')) {
            $setting = DB::table('platform_settings')->where('key', 'system_version')->first();
            if ($setting && $setting->payload !== null) {
                $decoded = json_decode($setting->payload, true);
                if (is_string($decoded) && $decoded !== '') {
                    $dbVersion = $decoded;
                }
            }
        }

        $codebaseVersion = VersionUpdateSeeder::NEW_VERSION;
        $comparison = version_compare($codebaseVersion, $dbVersion);

        $status = match (true) {
            $comparison > 0 => 'update_available',
            $comparison < 0 => 'mismatch',
            default => 'up_to_date',
        };

        return [
            'current_version' => $dbVersion,
            'new_version' => $codebaseVersion,
            'status' => $status,
            'laravel_version' => app()->version(),
            'php_version' => PHP_VERSION,
            'environment' => app()->environment(),
        ];
    }

    /**
     * Detect Git or CI/CD deployment state and compare against last recorded sync.
     */
    public function getGitDeploymentInfo(): array
    {
        $source = 'snapshot';
        $sourceLabel = 'Deployed Codebase';
        $branch = null;
        $commit = null;
        $commitMessage = null;
        $deployedAt = null;
        $pipeline = null;

        // 1. Check optional CI/CD deploy metadata file if generated by pipeline
        foreach ([base_path('.deploy-meta.json'), storage_path('app/deploy-meta.json')] as $metaPath) {
            if (File::exists($metaPath)) {
                $decoded = json_decode((string) File::get($metaPath), true);
                if (is_array($decoded)) {
                    $source = 'ci_metadata';
                    $sourceLabel = 'CI/CD Pipeline Metadata';
                    $branch = $decoded['branch'] ?? $branch;
                    $commit = isset($decoded['commit']) ? substr((string) $decoded['commit'], 0, 7) : $commit;
                    $commitMessage = $decoded['message'] ?? $commitMessage;
                    $pipeline = $decoded['pipeline'] ?? null;
                    if (! empty($decoded['deployed_at'])) {
                        $deployedAt = $this->safeParseDate((string) $decoded['deployed_at']);
                    }
                    break;
                }
            }
        }

        // 2. Check standard CI/CD environment variables
        $envCommit = env('DEPLOY_COMMIT') ?: env('GITHUB_SHA') ?: env('CI_COMMIT_SHORT_SHA');
        $envBranch = env('DEPLOY_BRANCH') ?: env('GITHUB_REF_NAME') ?: env('CI_COMMIT_REF_NAME');

        if ($commit === null && $envCommit) {
            $source = 'ci_env';
            $sourceLabel = 'CI/CD Environment';
            $commit = substr((string) $envCommit, 0, 7);
        }
        if ($branch === null && $envBranch) {
            $branch = (string) $envBranch;
        }
        if ($deployedAt === null && env('DEPLOYED_AT')) {
            $deployedAt = $this->safeParseDate((string) env('DEPLOYED_AT'));
        }

        // 3. Check Git worktree if .git exists
        if (File::exists(base_path('.git'))) {
            $gitInfo = $this->readGitWorktreeInfo();
            if ($gitInfo['commit'] !== null || $gitInfo['branch'] !== null) {
                $source = 'git';
                $sourceLabel = 'Git Worktree';
                $branch ??= $gitInfo['branch'];
                $commit ??= $gitInfo['commit'];
                $commitMessage ??= $gitInfo['message'];
                $deployedAt ??= $gitInfo['committed_at'];
            }
        }

        // 4. Fallback timestamp from composer.lock / app bootstrap mtime
        if ($deployedAt === null) {
            $marker = File::exists(base_path('composer.lock'))
                ? base_path('composer.lock')
                : base_path('bootstrap/app.php');
            if (File::exists($marker)) {
                $deployedAt = Carbon::createFromTimestamp(File::lastModified($marker));
            }
        }

        $lastSync = $this->getLastSyncRecord();
        $lastSyncAt = ! empty($lastSync['synced_at']) ? $this->safeParseDate($lastSync['synced_at']) : null;
        $lastSyncedCommit = $lastSync['commit'] ?? null;
        $newCommitDetected = $commit !== null && $lastSyncedCommit !== null && $commit !== $lastSyncedCommit;

        return [
            'source' => $source,
            'source_label' => $sourceLabel,
            'branch' => $branch,
            'commit' => $commit,
            'commit_message' => $commitMessage,
            'pipeline' => $pipeline,
            'deployed_at' => $deployedAt,
            'last_sync_at' => $lastSyncAt,
            'last_synced_commit' => $lastSyncedCommit,
            'last_synced_laravel' => $lastSync['laravel_version'] ?? null,
            'new_commit_detected' => $newCommitDetected,
        ];
    }

    /**
     * Inspect pending and completed Laravel database migrations.
     */
    public function getPendingMigrations(): array
    {
        try {
            $migrator = app('migrator');
            $paths = array_merge([database_path('migrations')], $migrator->paths());
            $files = $migrator->getMigrationFiles($paths);
            $ran = $migrator->repositoryExists() ? $migrator->getRepository()->getRan() : [];
            $pending = array_values(array_diff(array_keys($files), $ran));

            return [
                'count' => count($pending),
                'ran_count' => count($ran),
                'total_count' => count($files),
                'pending' => $pending,
            ];
        } catch (\Throwable $e) {
            return [
                'count' => 0,
                'ran_count' => 0,
                'total_count' => 0,
                'pending' => [],
                'error' => $e->getMessage(),
            ];
        }
    }

    /**
     * Check runtime storage, database, and cache optimization status.
     */
    public function getReadinessChecks(): array
    {
        $databaseConnected = false;
        try {
            DB::connection()->getPdo();
            $databaseConnected = true;
        } catch (\Throwable) {
            $databaseConnected = false;
        }

        $storagePath = public_path('storage');

        return [
            'database_connected' => $databaseConnected,
            'storage_linked' => is_link($storagePath) || File::isDirectory($storagePath),
            'storage_writable' => is_writable(storage_path()),
            'config_cached' => app()->configurationIsCached(),
            'routes_cached' => app()->routesAreCached(),
        ];
    }

    /**
     * Persist metadata for the most recent successful post-deploy synchronization.
     */
    public function recordSyncCompleted(?string $commit, string $version): void
    {
        if (! Schema::hasTable('platform_settings')) {
            return;
        }

        $payload = [
            'synced_at' => now()->toIso8601String(),
            'commit' => $commit,
            'app_version' => $version,
            'laravel_version' => app()->version(),
            'php_version' => PHP_VERSION,
        ];

        DB::table('platform_settings')->updateOrInsert(
            [
                'group' => 'general',
                'key' => 'last_deployment_sync',
            ],
            [
                'type' => 'json',
                'payload' => json_encode($payload),
                'updated_at' => now(),
                'created_at' => now(),
            ]
        );
    }

    /**
     * Read Git metadata safely via Symfony Process or .git/HEAD fallback.
     */
    protected function readGitWorktreeInfo(): array
    {
        $branch = null;
        $commit = null;
        $message = null;
        $committedAt = null;

        try {
            $process = new Process(['git', 'log', '-1', '--pretty=format:%h%n%s%n%cI'], base_path());
            $process->setTimeout(3);
            $process->run();

            if ($process->isSuccessful()) {
                $lines = explode("\n", trim($process->getOutput()));
                $commit = $lines[0] ?? null;
                $message = $lines[1] ?? null;
                $committedAt = ! empty($lines[2]) ? $this->safeParseDate($lines[2]) : null;
            }

            $branchProcess = new Process(['git', 'rev-parse', '--abbrev-ref', 'HEAD'], base_path());
            $branchProcess->setTimeout(3);
            $branchProcess->run();
            if ($branchProcess->isSuccessful()) {
                $branch = trim($branchProcess->getOutput()) ?: null;
            }
        } catch (\Throwable) {
            // Fallback to reading .git/HEAD when proc_open / git binary is unavailable
            $headFile = base_path('.git/HEAD');
            if (File::exists($headFile)) {
                $head = trim((string) File::get($headFile));
                if (str_starts_with($head, 'ref: ')) {
                    $ref = substr($head, 5);
                    $branch = basename($ref);
                    $refFile = base_path('.git/' . $ref);
                    if (File::exists($refFile)) {
                        $commit = substr(trim((string) File::get($refFile)), 0, 7);
                    }
                } else {
                    $commit = substr($head, 0, 7);
                }
            }
        }

        return [
            'branch' => $branch,
            'commit' => $commit,
            'message' => $message,
            'committed_at' => $committedAt,
        ];
    }

    /**
     * Retrieve the last recorded deployment sync record from platform_settings.
     */
    protected function getLastSyncRecord(): array
    {
        if (! Schema::hasTable('platform_settings')) {
            return [];
        }

        $row = DB::table('platform_settings')
            ->where('group', 'general')
            ->where('key', 'last_deployment_sync')
            ->first();

        if (! $row || ! $row->payload) {
            return [];
        }

        $decoded = json_decode($row->payload, true);

        return is_array($decoded) ? $decoded : [];
    }

    /**
     * Parse an ISO/date string safely without throwing on invalid inputs.
     */
    protected function safeParseDate(string $value): ?Carbon
    {
        try {
            return Carbon::parse($value);
        } catch (\Throwable) {
            return null;
        }
    }
}

